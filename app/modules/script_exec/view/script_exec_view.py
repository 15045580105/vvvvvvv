from PyQt5 import QtWidgets, QtCore, QtGui

from app.common.ui.widgets import ModernButton
from app.presentation.views.base_view import BaseView


class ScriptExecView(BaseView):
    def setup_ui(self):
        layout = QtWidgets.QHBoxLayout(self)
        layout.setSpacing(8)
        left_panel = QtWidgets.QGroupBox("📝 脚本列表")
        left_layout = QtWidgets.QVBoxLayout()
        self.script_list = QtWidgets.QListWidget()
        left_layout.addWidget(self.script_list)
        btn_layout = QtWidgets.QHBoxLayout()
        btn_layout.addWidget(ModernButton("上传", "#0EA5E9", "⬆️"))
        btn_layout.addWidget(ModernButton("刷新", "#059669", "🔄"))
        left_layout.addLayout(btn_layout)
        left_panel.setLayout(left_layout)
        center_panel = QtWidgets.QGroupBox("✏️ 脚本编辑器")
        center_layout = QtWidgets.QVBoxLayout()
        self.script_editor = QtWidgets.QTextEdit()
        self.script_editor.setPlaceholderText("# 在这里编辑Python脚本...\nimport os\nprint('Hello Diagnostic Tool')")
        self.script_editor.setFont(QtGui.QFont("Consolas", 10))
        center_layout.addWidget(self.script_editor)
        center_panel.setLayout(center_layout)
        right_panel = QtWidgets.QGroupBox("▶️ 执行控制")
        right_layout = QtWidgets.QVBoxLayout()
        right_layout.setSpacing(12)
        param_layout = QtWidgets.QFormLayout()
        param_layout.setSpacing(12)
        self.timeout_spin = QtWidgets.QSpinBox()
        self.timeout_spin.setRange(10, 3600)
        self.timeout_spin.setValue(300)
        self.timeout_spin.setSuffix(" 秒")
        param_layout.addRow("⏱️ 超时时间:", self.timeout_spin)
        self.engine_combo = QtWidgets.QComboBox()
        self.engine_combo.addItems(["Python 3.8", "Shell/Bash"])
        param_layout.addRow("🖥️ 执行引擎:", self.engine_combo)
        right_layout.addLayout(param_layout)
        right_layout.addStretch()
        self.run_btn = ModernButton("运行脚本", "#059669", "▶️")
        self.stop_btn = ModernButton("停止执行", "#EF4444", "⏹️")
        right_layout.addWidget(self.run_btn)
        right_layout.addWidget(self.stop_btn)
        output_group = QtWidgets.QGroupBox("📋 执行输出")
        output_layout = QtWidgets.QVBoxLayout()
        self.script_output = QtWidgets.QTextEdit()
        self.script_output.setReadOnly(True)
        self.script_output.setMaximumHeight(250)
        self.script_output.setFont(QtGui.QFont("Consolas", 10))
        output_layout.addWidget(self.script_output)
        output_group.setLayout(output_layout)
        right_layout.addWidget(output_group)
        right_panel.setLayout(right_layout)
        splitter = QtWidgets.QSplitter(QtCore.Qt.Horizontal)
        splitter.addWidget(left_panel)
        splitter.addWidget(center_panel)
        splitter.addWidget(right_panel)
        splitter.setSizes([200, 600, 300])
        layout.addWidget(splitter)

    def populate(self, scripts):
        self.script_list.clear()
        for s in scripts:
            self.script_list.addItem(f"📝 {s}")
